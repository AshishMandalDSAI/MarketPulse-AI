"""Shared pytest configuration.

The demo dataset's processed outputs (data/processed/) are generated by the
analytics pipeline and are git-ignored, so a fresh checkout or ZIP does not
contain them. Several existing tests (demo simulator, channel attribution,
regression guards) read those outputs. This session fixture generates them
once when they are missing, using the same steps as the dashboard's
"Initialize Demo Data" button.

The pipeline also rewrites models/ (the fitted demo MMM). To avoid silently
changing shipped model artifacts, models/ is backed up before generation and
restored afterwards.
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
_MARKER = ROOT / "data" / "processed" / "marketing_data_clean.csv"
_PIPELINE_STEPS = [
    "src/data/generate_dataset.py",
    "src/data/data_cleaning.py",
    "src/features/feature_engineering.py",
    "src/analytics/marketing_analytics.py",
    "src/models/marketing_mix_model.py",
    "src/models/model_evaluation.py",
    "src/models/channel_contribution.py",
    "src/optimization/budget_optimizer.py",
    "src/optimization/simulator.py",
    "src/forecasting/forecast.py",
    "src/utils/database.py",
]


@pytest.fixture(scope="session", autouse=True)
def ensure_demo_pipeline_outputs():
    """Generate demo pipeline outputs once per session if they are missing."""
    if _MARKER.exists():
        yield
        return

    models_dir = ROOT / "models"
    backup = None
    if models_dir.exists():
        backup = Path(tempfile.mkdtemp(prefix="mp_models_backup_")) / "models"
        shutil.copytree(models_dir, backup)

    try:
        for step in _PIPELINE_STEPS:
            result = subprocess.run(
                [sys.executable, "-I", step], cwd=str(ROOT),
                capture_output=True, text=True,
            )
            if result.returncode != 0:
                pytest.fail(
                    f"Demo pipeline step failed: {step}\n{result.stderr[-800:]}",
                    pytrace=False,
                )
    finally:
        if backup is not None:
            shutil.rmtree(models_dir, ignore_errors=True)
            shutil.copytree(backup, models_dir)
            shutil.rmtree(backup.parent, ignore_errors=True)
    yield
